// Compiles contracts/*.sol with the pinned solc-js (see package.json) and writes:
//   contracts/artifacts/<Name>.json              abi + bytecode + compiler metadata (used by tests / local deploys)
//   src/lib/contract/missionev.abi.ts            the MissionEV ABI as a typed `as const` (used by the app)
// Run: npm run contract:compile
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const sources = {};
const collect = (dir, prefix) => {
  if (!existsSync(dir)) return;
  for (const f of readdirSync(dir)) if (f.endsWith(".sol")) sources[`${prefix}${f}`] = { content: readFileSync(join(dir, f), "utf8") };
};
collect(join(root, "contracts"), "");
collect(join(root, "contracts", "proposed"), "proposed/");

const settings = { optimizer: { enabled: true, runs: 200 }, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } } };
const out = JSON.parse(solc.compile(JSON.stringify({ language: "Solidity", sources, settings })));

let failed = false;
for (const e of out.errors ?? []) {
  console.log(`${e.severity.toUpperCase()}: ${e.formattedMessage.trim()}`);
  if (e.severity === "error") failed = true;
}
if (failed) process.exit(1);

mkdirSync(join(root, "contracts", "artifacts"), { recursive: true });
for (const [file, contracts] of Object.entries(out.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    const artifact = {
      contractName: name,
      source: file,
      compiler: { name: "solc-js", version: solc.version(), settings },
      abi: c.abi,
      bytecode: `0x${c.evm.bytecode.object}`,
      deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
    };
    const outName = file.startsWith("proposed/") ? `${name}.proposed.json` : `${name}.json`;
    writeFileSync(join(root, "contracts", "artifacts", outName), `${JSON.stringify(artifact, null, 2)}\n`);
    console.log(`compiled ${file}:${name} -> contracts/artifacts/${outName} (${(artifact.deployedBytecode.length - 2) / 2} bytes deployed)`);
  }
}

const abi = out.contracts["MissionEV.sol"].MissionEV.abi;
mkdirSync(join(root, "src", "lib", "contract"), { recursive: true });
writeFileSync(
  join(root, "src", "lib", "contract", "missionev.abi.ts"),
  `// GENERATED by scripts/compile-contract.mjs from contracts/MissionEV.sol (solc ${solc.version()}). Do not edit by hand.\n` +
    `export const MISSIONEV_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log("wrote src/lib/contract/missionev.abi.ts");
